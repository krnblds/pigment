"""Smart models: one TOML manifest per asset, city/models/<kind>/<name>.toml.

Sections (all optional except [model]):

  [model]      name, kind, title, family, derived = [fields refreshed by `city discover --refresh`]
  [mesh]       how the geometry is made: runner (blender | python | file), generator, args, outputs,
               deps, params (passed to the generator as $CITY_PARAMS JSON; see Prop.param())
  [recipe]     the script that *writes* the Pigment script: runner, tool, job / args, outputs
  [pigment]    the Pigment scripts (scripts = [...]), their variants, decals and decal slots (read
               from the scripts), texture outputs, resolution, and `patch` ops applied before running
  [export]     game export of the textured asset (props, vehicles): runner, tool, args, outputs
  [decals]     decal sets: generator, outputs, images, which models use each image
  [game]       game rules: category, collision, policy (loader streaming), proxy, lod, lights,
               world_keys (mesh keys in world_layout.json), images
  [placement]  where the world puts it: counts per district, scatter rules (read-only copy), source
  [world] / [terrain] / [district] + [config]: the world and its parts; [config] is deep-merged
               into tools/world/world_config.json before the world is generated
"""
import copy
from pathlib import Path

from . import paths, toml_io

KINDS = ("building", "prop", "vehicle", "road_set", "decal_set", "tile_set", "sky", "terrain", "district", "world")
SECTIONS = ("model", "mesh", "recipe", "pigment", "export", "decals", "game", "placement", "world", "terrain", "district",
            "config")
RUNNERS = ("blender", "python", "file", "town_textures", "town_textures_world")

HEADER = """Smart model ({kind}/{name}). Generated by `python -m tools.city discover`; edit freely.
Fields listed in model.derived are facts read from the pipeline and are refreshed by
`city discover --refresh`; everything else is kept. See docs/CITY_BUILD.md."""

COMMENTS = {
    "mesh": "Geometry. params are passed to the generator as $CITY_PARAMS (JSON).",
    "recipe": "Writes the Pigment script below (without running Pigment).",
    "pigment": "Pigment scripts run with pigment-mcp --script. patch ops are applied to the script first:\n"
               "  {match = {tool = \"add_layer\", name = \"Concrete\"}, set = {opacity = 0.8}}",
    "export": "Game export of the textured asset.",
    "game": "Game rules (Godot): collision, streaming policy, LOD / proxy, lights.",
    "placement": "Where the world places it (read from scenes/world/world.json; scatter rules live in the props catalog).",
    "config": "Deep-merged into tools/world/world_config.json before the world is generated.",
}


class ManifestError(ValueError):
    pass


def path_for(kind: str, name: str) -> Path:
    return paths.MODELS / kind / f"{name}.toml"


def model_id(doc) -> str:
    return f"{doc['model']['kind']}/{doc['model']['name']}"


def validate(doc: dict, where="") -> dict:
    m = doc.get("model")
    if not isinstance(m, dict) or not m.get("name") or not m.get("kind"):
        raise ManifestError(f"{where}: [model] needs name and kind")
    if m["kind"] not in KINDS:
        raise ManifestError(f"{where}: unknown kind {m['kind']!r} (one of {', '.join(KINDS)})")
    for k in doc:
        if k not in SECTIONS:
            raise ManifestError(f"{where}: unknown section [{k}]")
    for sec in ("mesh", "recipe", "export", "decals"):
        s = doc.get(sec)
        if s is not None and s.get("runner", "file") not in RUNNERS:
            raise ManifestError(f"{where}: [{sec}] runner must be one of {RUNNERS}")
    pig = doc.get("pigment")
    if pig is not None:
        if not isinstance(pig.get("scripts", []), list):
            raise ManifestError(f"{where}: pigment.scripts must be a list")
        for p in pig.get("patch", []):
            if not isinstance(p, dict) or not ({"match", "append"} & set(p)):
                raise ManifestError(f"{where}: pigment.patch entries need `match` (+ `set`) or `append`")
    return doc


def load(path) -> dict:
    doc = toml_io.load(path)
    return validate(doc, paths.rel(path))


def save(doc: dict, path=None):
    path = Path(path or path_for(doc["model"]["kind"], doc["model"]["name"]))
    path.parent.mkdir(parents=True, exist_ok=True)
    toml_io.dump(_clean(doc), path, HEADER.format(kind=doc["model"]["kind"], name=doc["model"]["name"]), COMMENTS)


def _clean(v):
    if isinstance(v, dict):
        return {k: _clean(x) for k, x in v.items() if x is not None}
    if isinstance(v, (list, tuple)):
        return [_clean(x) for x in v if x is not None]
    return v


def load_all(root=None) -> dict:
    root = Path(root or paths.MODELS)
    out = {}
    for p in sorted(root.glob("*/*.toml")):
        doc = load(p)
        doc["_path"] = paths.rel(p)
        out[model_id(doc)] = doc
    return out


def _get(d, dotted):
    for k in dotted.split("."):
        if not isinstance(d, dict) or k not in d:
            return None
        d = d[k]
    return d


def _set(d, dotted, v):
    ks = dotted.split(".")
    for k in ks[:-1]:
        d = d.setdefault(k, {})
    if v is None:
        d.pop(ks[-1], None)
    else:
        d[ks[-1]] = v


def refresh(old: dict, new: dict) -> dict:
    """Keep the user's manifest; take only the derived fields from the fresh discovery."""
    out = copy.deepcopy(old)
    out.pop("_path", None)
    for f in new["model"].get("derived", []):
        _set(out, f, copy.deepcopy(_get(new, f)))
    out["model"]["derived"] = new["model"].get("derived", [])
    # sections the old manifest lacks entirely come from the new one
    for k, v in new.items():
        if k not in out:
            out[k] = copy.deepcopy(v)
    return out


def deep_merge(base, over):
    """Dicts merge recursively; lists of dicts with "name" merge by name; anything else replaces."""
    if isinstance(base, dict) and isinstance(over, dict):
        out = dict(base)
        for k, v in over.items():
            out[k] = deep_merge(base.get(k), v) if k in base else copy.deepcopy(v)
        return out
    if isinstance(base, list) and isinstance(over, list) and all(isinstance(x, dict) and "name" in x for x in base + over):
        out = [copy.deepcopy(x) for x in base]
        for o in over:
            i = next((j for j, x in enumerate(out) if x["name"] == o["name"]), None)
            if i is None:
                out.append(copy.deepcopy(o))
            else:
                out[i] = deep_merge(out[i], o)
        return out
    return copy.deepcopy(over)
