"""Headless driver for the hillside town (Blender 5.2, Cycles).

    blender -b --factory-startup --python tools/town_layout_driver.py -- [options]

Options (after "--"):
    --no-render          build and save only
    --no-save            do not save scenes/town/cyberpunk_town.blend
    --samples N          Cycles samples (default 128)
    --res WxH            render size (default 1600x900)
    --shots a,b,...      subset of: overview, yfork, tjunction, crossroads, stairs

Steps: import assets/town/*.glb into the TownKit collection as KIT_<asset>,
apply the Pigment maps from scenes/town/textures/<asset>/ (roads use the
shared tiles, trim sheet and decal atlas in scenes/town/textures/roads/, made
by `python tools/road_textures.py --run`), run
tools/blender_town.py, render night shots to docs/agents/town-layout/ and save
scenes/town/cyberpunk_town.blend.
"""
import glob
import math
import os
import sys
import time

import bpy
from mathutils import Vector

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "docs", "agents", "town-layout")
ARGS = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []


def opt(name, default=None):
    if name in ARGS:
        i = ARGS.index(name)
        return ARGS[i + 1] if i + 1 < len(ARGS) and not ARGS[i + 1].startswith("--") else True
    return default


def load_tool(name, extra=None):
    ns = {"__name__": name, "__file__": os.path.join(ROOT, "tools", name + ".py")}
    ns.update(extra or {})
    src = os.path.join(ROOT, "tools", name + ".py")
    exec(compile(open(src, encoding="utf-8").read(), src, "exec"), ns)
    return ns


def import_kit():
    kit = bpy.data.collections.get("TownKit") or bpy.data.collections.new("TownKit")
    if kit.name not in bpy.context.scene.collection.children:
        bpy.context.scene.collection.children.link(kit)
    for path in sorted(glob.glob(os.path.join(ROOT, "assets", "town", "*.glb"))):
        asset = os.path.splitext(os.path.basename(path))[0]
        if asset.startswith("junction_"):
            continue        # generated by the layout itself
        before = set(bpy.data.objects)
        bpy.ops.import_scene.gltf(filepath=path)
        new = [o for o in bpy.data.objects if o not in before]
        meshes = [o for o in new if o.type == "MESH"]
        for o in bpy.context.view_layer.objects:
            o.select_set(False)
        for o in meshes:
            o.select_set(True)
        bpy.context.view_layer.objects.active = meshes[0]
        if len(meshes) > 1:
            bpy.ops.object.join()
        obj = bpy.context.view_layer.objects.active
        bpy.ops.object.parent_clear(type="CLEAR_KEEP_TRANSFORM")
        bpy.ops.object.transform_apply(location=True, rotation=True, scale=True)
        for o in new:
            if o != obj and o.name in bpy.data.objects:
                bpy.data.objects.remove(o)
        obj.name = "KIT_" + asset
        obj.data.name = "KIT_" + asset
        for c in list(obj.users_collection):
            c.objects.unlink(obj)
        kit.objects.link(obj)
    bpy.context.view_layer.layer_collection.children[kit.name].exclude = True
    return kit


def apply_kit_materials():
    apply = load_tool("blender_pigment")["apply_pigment_material"]
    tex = os.path.join(ROOT, "scenes", "town", "textures")
    for obj in bpy.data.collections["TownKit"].objects:
        asset = obj.name[4:]
        folder = os.path.join(tex, asset)
        if os.path.isfile(os.path.join(folder, asset + "_BaseColor.png")):
            apply(obj, folder, asset)
        else:
            print("no Pigment maps for", asset)


def setup_render(samples, res):
    sc = bpy.context.scene
    sc.render.engine = "CYCLES"
    prefs = bpy.context.preferences.addons["cycles"].preferences
    for dev in ("OPTIX", "CUDA"):
        try:
            prefs.compute_device_type = dev
            prefs.get_devices()
            if any(d.type == dev for d in prefs.devices):
                for d in prefs.devices:
                    d.use = d.type == dev
                sc.cycles.device = "GPU"
                print("Cycles device", dev)
                break
        except TypeError:
            continue
    sc.cycles.samples = samples
    sc.cycles.use_denoising = True
    sc.cycles.max_bounces = 6
    sc.cycles.volume_bounces = 1
    sc.cycles.volume_step_rate = 4.0
    sc.render.resolution_x, sc.render.resolution_y = res
    sc.render.resolution_percentage = 100
    sc.render.image_settings.file_format = "PNG"
    sc.render.image_settings.color_mode = "RGB"
    sc.render.image_settings.compression = 90
    try:
        sc.view_settings.view_transform = "AgX"
        sc.view_settings.look = "AgX - Punchy"
    except TypeError:
        pass
    sc.view_settings.exposure = 0.6


def aim(cam, loc, target, lens):
    cam.location = loc
    cam.rotation_euler = (Vector(target) - Vector(loc)).to_track_quat("-Z", "Y").to_euler()
    cam.data.lens = lens


def shots(info):
    J = info["junctions"]
    runs = info["runs"]
    out = {}
    out["overview"] = ((-40.0, -110.0, 120.0), (15.0, 25.0, 0.0), 30)
    j2 = J["J2"]["pos"]
    p, t = runs[1].at(runs[1].length - 40)
    out["yfork"] = ((p.x - t.y * 2.2, p.y + t.x * 2.2, p.z + 1.7), (j2[0], j2[1], j2[2] + 3.5), 22)
    j3 = J["J3"]["pos"]
    p, t = runs[6].at(34)
    out["tjunction"] = ((p.x + t.y * 2.0, p.y - t.x * 2.0, p.z + 1.7), (j3[0], j3[1], j3[2] + 3.0), 22)
    j1 = J["J1"]["pos"]
    p, t = runs[8].at(30)
    out["crossroads"] = ((p.x - t.y * 2.0, p.y + t.x * 2.0, p.z + 6.0), (j1[0], j1[1], j1[2] + 1.0), 22)
    if info["stairs"]:
        # the stair with the clearest view from its low side
        dg = bpy.context.evaluated_depsgraph_get()
        sc = bpy.context.scene
        lvl = info["level"]
        best = None
        for st in info["stairs"]:
            a, b = Vector(st["from"]), Vector(st["to"])
            mid = (a + b) / 2
            tgt = Vector((mid.x, mid.y, mid.z + 0.5))
            d = (b - a).to_2d().normalized()
            for sgn in (1, -1):
                for dist in (9.0, 12.0, 15.0):
                    for back in (-4.0, -7.0, 0.0):
                        c = mid.to_2d() + Vector((-d.y, d.x)) * sgn * dist + d * back
                        g = lvl(c.x, c.y)
                        if abs(g - a.z) > 1.0:
                            continue
                        loc = Vector((c.x, c.y, g + 1.7))
                        ray = loc - tgt
                        hit = sc.ray_cast(dg, tgt + ray.normalized() * 2.5, ray.normalized(), distance=ray.length - 2.5)
                        if hit[0]:
                            continue
                        score = st["steps"] - abs(Vector(st["from"]).to_2d().length) * 0.02
                        if best is None or score > best[0]:
                            best = (score, tuple(loc), tuple(tgt))
                        break
        if best:
            out["stairs"] = (best[1], best[2], 20)
    return out


def daylight():
    """Debug lighting: grey sky, strong sun, no fog."""
    w = bpy.context.scene.world
    nt = w.node_tree
    for n in nt.nodes:
        if n.type == "BACKGROUND":
            n.inputs["Color"].default_value = (0.5, 0.55, 0.65, 1)
            n.inputs["Strength"].default_value = 1.0
    for l in list(nt.links):
        if l.to_socket.name == "Volume":
            nt.links.remove(l)
    bpy.data.objects["Moon"].data.energy = 3.0


def debug_shots(info, cam):
    """Orthographic top views of every junction and oblique day views."""
    out = {}
    for name, j in info["junctions"].items():
        x, y, z = j["pos"]
        out["top_" + name] = ((x, y, z + 100), (x, y, z), 70.0)
        out["obl_" + name] = ((x - 35, y - 45, z + 30), (x, y, z), 28)
    for name, v in shots(info).items():
        out["day_" + name] = v
    return out


def verify(samples=20000, seed=3):
    """Terrain never above road/sidewalk tops; street furniture and buildings
    rest on something.  Prints counts; returns a dict."""
    import random
    from mathutils.bvhtree import BVHTree
    rng = random.Random(seed)
    coll = bpy.data.collections["CyberpunkTown"]
    dg = bpy.context.evaluated_depsgraph_get()
    terrain = coll.objects["TownTerrain"]
    tb = BVHTree.FromObject(terrain, dg)
    roads = [o for o in coll.objects if o.name.startswith(("RoadRun", "Junction_"))]
    tops = []
    for o in roads:
        mw = o.matrix_world
        for p in o.data.polygons:
            if p.normal.z > 0.9 and p.area > 0.01:
                tops.append((o, p.index))
    poke = 0
    worst = 0.0
    for _ in range(samples):
        o, i = rng.choice(tops)
        p = o.data.polygons[i]
        vs = [o.matrix_world @ o.data.vertices[v].co for v in p.vertices]
        w = [rng.random() for _ in vs]
        c = sum((v * k for v, k in zip(vs, w)), Vector()) / sum(w)
        hit = tb.ray_cast(Vector((c.x, c.y, c.z + 20)), Vector((0, 0, -1)), 40)
        if hit[0] is not None and hit[0].z > c.z + 0.002:
            poke += 1
            worst = max(worst, hit[0].z - c.z)
    # supports: everything that should stand on the ground
    ground = [terrain] + roads + [o for o in coll.objects if o.name.startswith(("Stairs", "RetainingWall", "Footing"))]
    gb = []
    for o in ground:
        try:
            gb.append(BVHTree.FromObject(o, dg))
        except Exception:
            pass
    floating = []
    for o in coll.objects:
        if not o.name.startswith(("StreetLamp", "PowerPole", "building_")) or o.parent is not None:
            continue
        loc = o.matrix_world.translation
        best = 1e9
        for b in gb:
            h = b.ray_cast(Vector((loc.x, loc.y, loc.z + 0.3)), Vector((0, 0, -1)), 50)
            if h[0] is not None:
                best = min(best, loc.z - h[0].z)
        if o.name.startswith("building_"):
            # footing child reaches below the lowest ground under the building
            continue
        if best > 0.05:
            floating.append((o.name, round(best, 3)))
    res = {"samples": samples, "terrain_above_road": poke, "worst_mm": round(worst * 1000, 1), "floating": floating[:20], "n_floating": len(floating)}
    print("VERIFY", res)
    return res


def main():
    t0 = time.time()
    bpy.ops.wm.read_factory_settings(use_empty=True)
    import_kit()
    apply_kit_materials()
    if opt("--layout"):
        # render another layout script (e.g. an older blender_town.py) from its own camera
        src = str(opt("--layout"))
        exec(compile(open(src, encoding="utf-8").read(), src, "exec"), {"__name__": "layout"})
        setup_render(int(opt("--samples", 128)), tuple(int(v) for v in str(opt("--res", "1600x900")).split("x")))
        os.makedirs(OUT, exist_ok=True)
        bpy.context.scene.render.filepath = os.path.join(OUT, str(opt("--out", "before")) + ".png")
        bpy.ops.render.render(write_still=True)
        return
    town = load_tool("blender_town", {"TOWN_NO_AUTOBUILD": True, "TOWN_ROOT": ROOT})
    info = town["build"](root=ROOT)
    print(f"built in {time.time() - t0:.0f} s")
    if opt("--verify"):
        verify()
    res = tuple(int(v) for v in str(opt("--res", "1600x900")).split("x"))
    setup_render(int(opt("--samples", 128)), res)
    if opt("--debug"):
        daylight()
        dbg = os.path.join(ROOT, "target", "debug_shots")
        os.makedirs(dbg, exist_ok=True)
        cam = bpy.context.scene.camera
        want = str(opt("--debug"))
        for name, (loc, tgt, lens) in debug_shots(info, cam).items():
            if want is not True and want != "True" and not any(w in name for w in want.split(",")):
                continue
            if name.startswith("top_"):
                cam.data.type = "ORTHO"
                cam.data.ortho_scale = lens
                cam.location = loc
                cam.rotation_euler = (0, 0, 0)
            else:
                cam.data.type = "PERSP"
                aim(cam, loc, tgt, lens)
            bpy.context.scene.render.filepath = os.path.join(dbg, name + ".png")
            bpy.ops.render.render(write_still=True)
        cam.data.type = "PERSP"
        return
    if not opt("--no-render"):
        os.makedirs(OUT, exist_ok=True)
        cam = bpy.context.scene.camera
        want = str(opt("--shots", "overview,yfork,tjunction,crossroads,stairs")).split(",")
        for name, (loc, tgt, lens) in shots(info).items():
            if name not in want:
                continue
            aim(cam, loc, tgt, lens)
            bpy.context.scene.render.filepath = os.path.join(OUT, name + ".png")
            t1 = time.time()
            bpy.ops.render.render(write_still=True)
            print(f"rendered {name} in {time.time() - t1:.0f} s")
        # leave the camera on the street-level shot
        loc, tgt, lens = shots(info)["yfork"]
        aim(cam, loc, tgt, lens)
    if not opt("--no-save"):
        path = os.path.join(ROOT, "scenes", "town", "cyberpunk_town.blend")
        bpy.ops.wm.save_as_mainfile(filepath=path, compress=True)
        bpy.ops.file.make_paths_relative()      # textures as //textures/..., portable
        bpy.ops.wm.save_mainfile(compress=True)
        print("saved", path)


main()
